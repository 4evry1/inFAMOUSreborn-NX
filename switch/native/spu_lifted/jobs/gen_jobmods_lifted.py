#!/usr/bin/env python3
"""Mechanical adaptation of the Windows port's lifted WWS job modules (infamous-recomp/spu/jobmod_*, register-cached twins)
so they compile against THIS repository's native SPU runtime and run through the hybrid glue (spu_lifted_hybrid.c, dynamic job
modules). Decision 104, 2026-11-13. Companion of native/spu_lifted/bink/gen_bink_lifted.py; read that one first.

usage: gen_jobmods_lifted.py --spu <infamous-recomp/spu> --out <dir> [--elf <EBOOT.elf>] [--only name,name,...] [--tasks <tasks.json>]

Task images (round 2, 2026-11-13): extra/tasks.json lists SPU ELFs of the EBOOT that are not WWS job modules but SPURS tasks (the Edge zlib inflate task,
unit spu_0000_at_005F6000, LS 0x3000). Their rc.c is renamed to jobmod_<first 6 bytes of the SpuGUID>_e<entry>, run through the same two passes the job
modules went through (ps3recomp/tools/spu_ibfast.py, spu_v200.py; run on a temporary copy, nothing in the checkout is written) and adapted like a
job module with base = the ELF's first PT_LOAD address. Needs --elf.

Inputs (read only): spu_recomp_rc.c, the module bytes jobmods/<name>.bin, jobmods_manifest.json, jobmods_extra_map.json, and
(optionally) the user's own EBOOT.elf, whose embedded SPU ELFs (spu_0002..0007) are the same programs as six of the modules and give
their exact section layout. Outputs under --out: <name>_rc.c (adapted text), <name>_module.c (rows + module descriptor), jobmods_table.c,
jobmods_report.json (what was adapted, what stays an escape, why).

What is changed in the lifted text (nothing that decides a result):
  1. the preamble and the tail (registry, pairs, constructor, the Windows ibf tables) are replaced: prelude include, per-site caches,
     a regenerated ibf lookup over THIS file's functions, the function prototypes;
  2. `lodx_*` hook lines (jobmod_50f371dc382d only: the Windows port's LOD enhancement hooks, defaults off) are removed;
  3. a function the generator cannot adapt EXACTLY becomes an escape stub (`ctx->pc = X; ps3_lifted_escape(ctx)`, row flag 0 = the
     interpreter runs it): any function with a word the lifter could not translate (data decoded as code), a constant branch that
     does not target a function of this file, a `stop` site that cannot be tied to exactly one stop word of the module, a
     SPU_XFER without a constant pc store before it;
  4. `spu_stop(ctx); return;` -> `ps3_lifted_stop_at(ctx, <address of the stop word>); return;` (address read from the module bytes);
     `spu_halt` assertion sites -> `ps3_lifted_halt_at(ctx, <pc>)`.
The module descriptor carries the 16-byte signature (module bytes 0..16) and the hash of the code range [0x4000, T): T is the first
writable section of the module's own ELF when the module has an EBOOT twin, else the end of the last function reachable from the
entry and the extra roots (jobmods_extra_map.json: the computed indirect targets the lifter was told about).
"""
import argparse, hashlib, json, os, re, struct, sys

MARK = 'GENERATED by gen_jobmods_lifted.py'
BASE = 0x4000


def fnv1a64(buf):
    h = 0xCBF29CE484222325
    for byte in buf:
        h ^= byte
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def hash64w(buf):
    """Same as ps3_spu_lifted_hash64w (spu_lifted_hybrid.c)."""
    M = 0xFFFFFFFFFFFFFFFF
    def mix(h, w):
        h = ((h ^ w) * 0x9E3779B97F4A7C15) & M
        return h ^ (h >> 32)
    h = [0x243F6A8885A308D3, 0x13198A2E03707344, 0xA4093822299F31D0, 0x082EFA98EC4E6C89]
    n = len(buf)
    i = 0
    while i + 32 <= n:
        for k in range(4):
            h[k] = mix(h[k], int.from_bytes(buf[i + 8 * k:i + 8 * k + 8], 'little'))
        i += 32
    while i + 8 <= n:
        h[0] = mix(h[0], int.from_bytes(buf[i:i + 8], 'little'))
        i += 8
    if i < n:
        h[0] = mix(h[0], int.from_bytes(bytes(buf[i:n]) + b'\0' * (8 - (n - i)), 'little'))
    return mix(mix(mix(mix(h[0], h[1]), h[2]), h[3]), n)


def elf_twins(elf_path):
    """{image bytes (PT_LOAD at BASE) -> (writable_start, elf name)} for the embedded SPU ELFs of the EBOOT."""
    out = {}
    if not elf_path or not os.path.exists(elf_path):
        return out
    data = open(elf_path, 'rb').read()
    offsets = {'spu_0000': 0x5F6000, 'spu_0001': 0x673E80, 'spu_0002': 0x68F900, 'spu_0003': 0x6A3300, 'spu_0004': 0x6BEF80,
               'spu_0005': 0x6D7200, 'spu_0006': 0x6F1900, 'spu_0007': 0x700100}
    for name, b in offsets.items():
        if data[b:b + 4] != b'\x7fELF':
            continue
        phoff = struct.unpack('>I', data[b + 28:b + 32])[0]
        phentsize, phnum = struct.unpack('>HH', data[b + 42:b + 46])
        seg = None
        for k in range(phnum):
            o = b + phoff + k * phentsize
            ptype, off, vaddr, _pa, filesz, memsz, flags, _al = struct.unpack('>IIIIIIII', data[o:o + 32])
            if ptype == 1 and vaddr == BASE:
                seg = (off, filesz)
        if not seg:
            continue
        image = data[b + seg[0]:b + seg[0] + seg[1]]
        shoff, = struct.unpack('>I', data[b + 32:b + 36])
        shentsize, shnum, shstrndx = struct.unpack('>HHH', data[b + 46:b + 52])
        writable = None
        sections = []
        for k in range(shnum):
            o = b + shoff + k * shentsize
            sections.append(struct.unpack('>IIIIIIIIII', data[o:o + 40]))
        strtab = data[b + sections[shstrndx][4]:b + sections[shstrndx][4] + sections[shstrndx][5]]
        for sname, typ, flags, addr, off, size, link, info, align, entsize in sections:
            label = strtab[sname:strtab.index(b'\0', sname)].decode()
            # .JobCheckData (0x4010, 32 bytes) is flagged writable but is part of the job's identity header: not data the job writes
            if typ == 1 and (flags & 1) and addr > BASE and size and label not in ('.SpuGUID', '.JobCheckData'):   # PROGBITS, SHF_WRITE
                if writable is None or addr < writable:
                    writable = addr
        out[image] = (writable, name)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--spu', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--elf')
    ap.add_argument('--only')
    ap.add_argument('--tasks', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'extra', 'tasks.json'))
    a = ap.parse_args()
    manifest = json.load(open(os.path.join(a.spu, 'jobmods_manifest.json')))
    extra_map = json.load(open(os.path.join(a.spu, 'jobmods_extra_map.json')))
    twins = elf_twins(a.elf)
    only = set(a.only.split(',')) if a.only else None
    os.makedirs(a.out, exist_ok=True)
    report = []
    table = []
    for index, m in enumerate(manifest):
        name = m['name']
        if only and name not in only and name[7:19] not in only:
            continue
        binary = open(os.path.join(a.spu, 'jobmods', name + '.bin'), 'rb').read()
        assert len(binary) == m['size']
        rc = open(os.path.join(a.spu, name, 'spu_recomp_rc.c'), 'rb').read()
        sha = hashlib.sha256(rc).hexdigest()
        text = rc.decode('utf-8')
        entry_pc = BASE + (m['entry_off'] if 'entry_off' in m else m['entry'] - BASE)
        info = adapt(name, text, binary, entry_pc, extra_map.get(name, []), twins)
        info['sha256_input'] = sha
        info['image_id'] = 200 + index
        info['entry_pc'] = entry_pc
        info['size'] = len(binary)
        emit(a.out, name, info, binary)
        report.append({k: v for k, v in info.items() if k not in ('c_text', 'rows')})
        table.append(name)
        print('%-28s functions=%d lifted=%d stubs=%d (lossy=%d bad_xfer=%d stop=%d other=%d plain=%d) reachable=%d reachable_stubs=%d halts=%d  T=0x%X (%s) range=%d bytes  text=%d KB' % (
            name, info['functions'], info['lifted'], info['stubs'], info['why']['lossy'], info['why']['bad_xfer'], info['why']['stop'],
            info['why']['other'], info['why']['plain_stub'], info['reachable_functions'], len(info['reachable_stubs']), info['halts'], info['T'], info['T_source'], info['T'] - BASE, len(info['c_text']) // 1024))
    # ---- task images (SPURS tasks lifted like jobs, base below the job window)
    if os.path.exists(a.tasks) and a.elf and os.path.exists(a.elf):
        elf_data = open(a.elf, 'rb').read()
        for spec in json.load(open(a.tasks)):
            task = load_task_unit(a.spu, elf_data, spec)
            name = task['name']
            if only and name not in only and name[7:19] not in only:
                continue
            info = adapt(name, task['text'], task['binary'], task['entry'], [], {}, base=task['base'], t_fixed=task['T'], hooks=task['hooks'], policy=task.get('policy'))
            info['sha256_input'] = task['sha256_input']
            info['image_id'] = 200 + len(table)
            info['entry_pc'] = task['entry']
            info['size'] = len(task['binary'])
            emit(a.out, name, info, task['binary'], task['base'], policy=task.get('policy'))
            open(os.path.join(os.path.dirname(os.path.abspath(a.tasks)), name + '.bin'), 'wb').write(task['binary'])   # for the host test (test_jobmods_lifted --extra)
            report.append({k: v for k, v in info.items() if k not in ('c_text', 'rows')})
            table.append(name)
            print('%-28s functions=%d lifted=%d stubs=%d (lossy=%d bad_xfer=%d stop=%d other=%d plain=%d) reachable=%d reachable_stubs=%d halts=%d  T=0x%X (%s) range=%d bytes  text=%d KB' % (
                name, info['functions'], info['lifted'], info['stubs'], info['why']['lossy'], info['why']['bad_xfer'], info['why']['stop'],
                info['why']['other'], info['why']['plain_stub'], info['reachable_functions'], len(info['reachable_stubs']), info['halts'], info['T'], info['T_source'], info['T'] - task['base'], len(info['c_text']) // 1024))
    json.dump(report, open(os.path.join(a.out, 'jobmods_report.json'), 'w'), indent=1)
    with open(os.path.join(a.out, 'jobmods_table.c'), 'w') as f:
        f.write('/* %s -- do not edit. The job modules the group runner may arm (Decision 104). A module is part of the table only when its\n'
                ' * PS3_JOBMOD_<name> is defined (lle.mk: LLE_SPU_JOBMODS). */\n#include "../../jobs/jobmods_table.h"\n' % MARK)
        for n in table:
            f.write('#ifdef PS3_JOBMOD_%s\nextern const ps3_spu_lifted_module %s_module;\n#endif\n' % (n, n))
        f.write('enum { PS3_JOBMODS_ENABLED = 0\n')
        for n in table:
            f.write('#ifdef PS3_JOBMOD_%s\n + 1\n#endif\n' % n)
        f.write('};\nconst ps3_spu_lifted_module *const ps3_jobmods_table[PS3_JOBMODS_ENABLED + 1] = {\n')
        for n in table:
            f.write('#ifdef PS3_JOBMOD_%s\n    &%s_module,\n#endif\n' % (n, n))
        f.write('    0 };\nconst unsigned ps3_jobmods_count = PS3_JOBMODS_ENABLED;\n')
        f.write('const char *const ps3_jobmods_all_names[] = {\n' + ''.join('    "%s",\n' % n for n in table) + '    0 };\n')
    print('wrote', len(table), 'modules')


CHANNELS = {'SPU_RdEventStat': 0, 'SPU_WrEventMask': 1, 'SPU_WrEventAck': 2, 'SPU_RdSigNotify1': 3, 'SPU_RdSigNotify2': 4, 'SPU_WrDec': 7, 'SPU_RdDec': 8, 'MFC_WrMSSyncReq': 9,
            'SPU_RdEventMask': 11, 'MFC_RdTagMask': 12, 'SPU_RdMachStat': 13, 'SPU_WrSRR0': 14, 'SPU_RdSRR0': 15, 'MFC_LSA': 16, 'MFC_EAH': 17, 'MFC_EAL': 18, 'MFC_Size': 19,
            'MFC_TagID': 20, 'MFC_Cmd': 21, 'MFC_WrTagMask': 22, 'MFC_WrTagUpdate': 23, 'MFC_RdTagStat': 24, 'MFC_RdListStallStat': 25, 'MFC_WrListStallAck': 26,
            'MFC_RdAtomicStat': 27, 'SPU_WrOutMbox': 28, 'SPU_RdInMbox': 29, 'SPU_WrOutIntrMbox': 30}
CHANNEL_CALL = re.compile(r'\bspu_(rdch|wrch|rchcnt)\(ctx, ([A-Za-z_0-9]+)')


def annotate_channels(body, pc, end, word_at):
    """Replace spu_rdch / spu_wrch of a function by ps3_lifted_rdch_at / ps3_lifted_wrch_at with the address of the channel instruction, or None when the statements and the
    instructions of the extent [pc, end) do not match one for one (kind, channel, order)."""
    calls = list(CHANNEL_CALL.finditer(body))
    kinds = {0x00D: 'rdch', 0x10D: 'wrch', 0x00F: 'rchcnt'}
    ops = []
    for a in range(pc, end, 4):
        w = word_at(a)
        if w is None:
            break
        if (w >> 21) in kinds:
            ops.append((kinds[w >> 21], (w >> 7) & 0x7F, a))
    if len(calls) != len(ops):
        return None
    out, last = [], 0
    for m, (kind, channel, address) in zip(calls, ops):
        if m.group(1) != kind or CHANNELS.get(m.group(2)) != channel:
            return None
        if kind == 'rchcnt':
            continue                      # never blocks: left as it is
        j = m.start() + len('spu_' + kind)
        depth = 0
        while True:
            c = body[j]
            if c == '(':
                depth += 1
            elif c == ')':
                depth -= 1
                if depth == 0:
                    break
            j += 1
        out.append(body[last:m.start()])
        out.append('ps3_lifted_%s_at(%s, 0x%05Xu)' % (kind, body[m.start() + len('spu_' + kind) + 1:j], address))
        last = j + 1
    out.append(body[last:])
    return ''.join(out)


def hash_ranges(binary, base, ranges):
    """ps3_spu_lifted_module_hash for a policy module."""
    M = 0xFFFFFFFFFFFFFFFF
    h = 0x9E3779B97F4A7C15
    for lo, hi in ranges:
        h = ((h ^ hash64w(binary[lo - base:hi - base])) * 0xFF51AFD7ED558CCD) & M
        h ^= h >> 32
    return h


def load_task_unit(spu_dir, elf_data, spec):
    """One SPU ELF of the EBOOT as a lifted module: {name, base, entry, binary, T, text, sha256_input}. The binary covers [base, end of the initialised
    data segment), zero padded between the segments; the code range (hash, DMA disarm) is the first (read-only, executable) segment only."""
    import subprocess, tempfile
    unit = spec['unit']
    policy = None
    if spec.get('kind') == 'policy':
        # a policy module (pm_wwsjob): a raw blob the SPURS kernel DMAs to LS `base`; no ELF. Identity = signature + the hash of its CODE ranges (the data between them changes).
        base = int(spec['base'], 0); entry = int(spec['entry'], 0)
        repo = os.path.normpath(os.path.join(spu_dir, '..', '..', 'switch'))   # <repo>/switch
        if 'blob_file' in spec:      # a body taken from libsre.prx, kept beside its lifter input (extra/lift_input/<unit>/PROVENANCE.txt)
            code = open(os.path.join(repo, spec['blob_file']), 'rb').read()
        else:
            off = int(spec['blob_offset'], 0); size = int(spec['blob_size'], 0)
            code = elf_data[off:off + size]
        binary = bytearray(code)
        ranges = [(int(lo, 0), int(hi, 0)) for lo, hi in spec['ranges']]
        assert 1 <= len(ranges) <= 4 and all(base <= lo < hi <= base + len(code) for lo, hi in ranges)
        policy = {'ranges': ranges, 'stub_ranges': [(int(lo, 0), int(hi, 0)) for lo, hi in spec.get('stub_ranges', [])],
                  'job_hook': int(spec['job_hook_function'], 0) if 'job_hook_function' in spec else None,
                  'module_kind': spec.get('module_kind', 'policy')}      # 'kernel': the SPURS kernel (PS3_LIFTED_KIND_KERNEL), whose body starts below its first code range (variables)
        sig_off = ranges[0][0] - base
        T_value = max(hi for lo, hi in ranges)
    else:
        b = int(spec['elf_offset'], 0) if isinstance(spec['elf_offset'], str) else spec['elf_offset']
        if elf_data[b:b + 4] != b'\x7fELF':
            sys.exit('no ELF at 0x%X for %s' % (b, unit))
        entry, phoff = struct.unpack('>II', elf_data[b + 24:b + 32])[0], struct.unpack('>I', elf_data[b + 28:b + 32])[0]
        phentsize, phnum = struct.unpack('>HH', elf_data[b + 42:b + 46])
        segs = []
        for k in range(phnum):
            o = b + phoff + k * phentsize
            ptype, off, vaddr, _pa, filesz, memsz, flags, _al = struct.unpack('>IIIIIIII', elf_data[o:o + 32])
            if ptype == 1:
                segs.append((vaddr, off, filesz, flags))
        code_seg = [x for x in segs if x[3] & 1][0]
        base, off, filesz = code_seg[0], code_seg[1], code_seg[2]
        code = elf_data[b + off:b + off + filesz]
        binary = bytearray(code)
        for vaddr, doff, dsize, flags in segs:
            if not (flags & 1) and dsize and vaddr >= base + len(binary):
                binary.extend(b'\0' * (vaddr - base - len(binary)))
                binary.extend(elf_data[b + doff:b + doff + dsize])
        T_value = base + len(code)
    sig_off = (policy['ranges'][0][0] - base) if policy else 0
    name = 'jobmod_%s_e%X' % (code[sig_off:sig_off + 16].hex()[:12], entry)
    rc_path = os.path.join(os.path.normpath(os.path.join(spu_dir, '..', '..', 'switch')), spec['input_dir'], 'spu_recomp_rc.c') if 'input_dir' in spec else os.path.join(spu_dir, unit, 'spu_recomp_rc.c')
    rc = open(rc_path, 'rb').read()
    text = rc.decode('utf-8', errors='surrogateescape').replace(unit, name)
    tools = os.path.normpath(os.path.join(spu_dir, '..', '..', 'ps3recomp', 'tools'))
    with tempfile.TemporaryDirectory() as tmp:
        d = os.path.join(tmp, name)
        os.makedirs(d)
        path = os.path.join(d, 'spu_recomp_rc.c')
        open(path, 'w', encoding='utf-8', errors='surrogateescape', newline='\n').write(text)
        for cmd in ([sys.executable, '-I', os.path.join(tools, 'spu_ibfast.py'), tmp], [sys.executable, '-I', os.path.join(tools, 'spu_v200.py'), path]):
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode:
                sys.exit('%s failed: %s' % (cmd[2], r.stderr[-400:]))
        text = open(path, encoding='utf-8', errors='surrogateescape').read()
    hooks = {int(k, 0): v for k, v in spec.get('hooks', {}).items()}
    return {'name': name, 'base': base, 'entry': entry, 'binary': bytes(binary), 'T': T_value, 'text': text,
            'sha256_input': hashlib.sha256(rc).hexdigest(), 'hooks': hooks, 'policy': policy}


def adapt(name, text, binary, entry_pc, extra_roots, twins, base=BASE, t_fixed=None, hooks=None, policy=None):
    prefix = name + '_rc_spu_func_'
    cut_tail = text.index('/* Function table */')
    body_full = text[:cut_tail]
    first_proto = body_full.index('/* v95: register-cached twins')
    preamble, rest = body_full[:first_proto], body_full[first_proto:]
    nsites = int(re.search(r's_ibf_c\[(\d+)\]', preamble).group(1))
    def_re = re.compile(r'^void (' + re.escape(prefix) + r'([0-9A-F]{8}))\(spu_context\* ctx\) \{\n(.*?)^\}\n', re.M | re.S)
    defs = list(def_re.finditer(rest))
    pcs = [int(m.group(2), 16) for m in defs]
    if len(set(pcs)) != len(pcs):
        sys.exit('duplicate function pcs in ' + name)
    names = {m.group(1): int(m.group(2), 16) for m in defs}
    protos = set(re.findall(r'^void (' + re.escape(prefix) + r'[0-9A-F]{8})\(spu_context\* ctx\);', rest, re.M))
    if protos != set(names):
        sys.exit('prototypes != definitions in %s (%d vs %d)' % (name, len(protos), len(names)))
    sorted_pcs = sorted(pcs)
    next_pc = {pc: (sorted_pcs[i + 1] if i + 1 < len(sorted_pcs) else base + len(binary)) for i, pc in enumerate(sorted_pcs)}

    def word_at(addr):
        o = addr - base
        return struct.unpack('>I', binary[o:o + 4])[0] if 0 <= o <= len(binary) - 4 else None

    xfer_re = re.compile(r'ctx->pc = (0x[0-9A-Fa-f]+); SPU_XFER\(ctx, (\w+)\)')
    stop_site = re.compile(r'ctx->stop_code = (0x[0-9A-Fa-f]+|[0-9]+)u; ctx->status = SPU_STATUS_STOPPED_BY_STOP; spu_stop\(ctx\);(?: return;)?')   # `return;` is absent when the stop ends the function
    halt_site = re.compile(r'extern void spu_halt\(spu_context\*\); (fprintf\(stderr, "\[spu\] HALT-ASSERT \w+ pc=0x([0-9A-F]+) img=%d\\n", ctx->image_id\);) '
                           r'ctx->status = SPU_STATUS_STOPPED_BY_HALT; spu_halt\(ctx\); return;')
    stub_body = re.compile(r'    ctx->pc = (0x[0-9A-F]+)u; g_spu_trampoline_fn = spu_indirect_branch; return;\n')
    lod_line = re.compile(r'^[ \t]*lodx\w*\([^;\n]*\);[^\n]*\n', re.M)

    why = {'lossy': 0, 'bad_xfer': 0, 'stop': 0, 'other': 0, 'plain_stub': 0, 'data': 0, 'channel': 0}
    stop_notes = []
    stub_reason = {}
    stopd_sites = 0
    hooked = []
    job_hooks_done = []
    rows = []            # (pc, function name, lifted?)
    graph = {}
    out_defs = []
    halts = 0
    ila_values = set()

    for m in defs:
        fname, pc, fbody = m.group(1), int(m.group(2), 16), m.group(3)
        fbody = lod_line.sub('', fbody)
        if 'lodx' in fbody:
            sys.exit('unremoved lodx hook in ' + fname)
        graph[pc] = set(names[n] for n in re.findall(re.escape(prefix) + r'[0-9A-F]{8}', fbody) if names.get(n) not in (None, pc))
        for v in re.findall(r'spu_ila\(0x([0-9A-F]+)\)', fbody):
            ila_values.add(int(v, 16))
        sm = stub_body.fullmatch(fbody)
        reason = None
        if sm:
            if int(sm.group(1), 16) != pc:
                sys.exit('stub pc/name mismatch in ' + fname)
            why['plain_stub'] += 1
            stub_reason[pc] = 'plain'
            rows.append((pc, fname, 0))
            out_defs.append('void %s(spu_context* ctx) {\n    ctx->pc = %su; ps3_lifted_escape(ctx);\n}\n' % (fname, sm.group(1)))
            continue
        if policy and any(lo <= pc < hi for lo, hi in policy['stub_ranges']):
            reason = 'data'       # a "function" the lifter made of data (the policy module's variables and tables between its code ranges)
        if 'spu_unsupported(' in fbody:
            reason = 'lossy'
        if not reason:
            # every SPU_XFER must follow a constant pc store and target the function that pc names
            if len(re.findall(r'SPU_XFER\(', fbody)) != len(xfer_re.findall(fbody)):
                reason = 'bad_xfer'
            else:
                for pchex, target in xfer_re.findall(fbody):
                    if target not in names or names[target] != int(pchex, 16):
                        reason = 'bad_xfer'
        new_body = fbody
        if not reason:
            stops = list(stop_site.finditer(new_body))
            end = next_pc[pc]
            # The lifter prints the code of a `stop` instruction in hex (`0x0u`, `0x2128u`) and the code of a `stopd` (op 0x140, the
            # compiler's trap after a call that never returns) as a decimal `0u`: a stopd carries no 14-bit code (the interpreter and the
            # lifter both take it as 0). Either one is an architectural stop that hands control back to the runner and may be resumed
            # at the next address, so the site becomes ps3_lifted_stop_at() with the address of the stop word, exactly as the interpreter
            # leaves its pc. (Before round 2 the decimal form was not matched against stopd words and every function holding one
            # was a stub: the task-main wrappers 0x40E4 / 0x8E74 / 0x17DC8 / 0x77B0 of the four task modules, hence 300 escapes per call.)
            sites = [(int(s.group(1), 0), not s.group(1).startswith('0x')) for s in stops]
            addr_of = {}
            for key in set(sites):
                code, is_stopd = key
                if is_stopd:
                    found = [at for at in range(pc, end, 4) if word_at(at) is not None and (word_at(at) >> 21) == 0x140]
                    if code != 0:
                        found = []
                else:
                    found = [at for at in range(pc, end, 4) if word_at(at) is not None and (word_at(at) >> 21) == 0 and (word_at(at) & 0x3FFF) == code]
                # `stop 0` is the compiler's trap (a call that never returns, then stop 0), followed by zero padding that decodes as more
                # `stop 0`: any of them will do, because the runner ends the thread at a stop 0 (it is not a service call) and the address
                # after it is only a log value. Every other stop code must match exactly one word of the function, and must be used by one site.
                if code == 0 and found:
                    found = found[:1]
                if len(found) != 1 or (code != 0 and sites.count(key) != 1):
                    reason = 'stop'
                    stop_notes.append('0x%X: stop%s code 0x%X, %d matching stop words in [0x%X,0x%X), %d sites with that code' % (pc, 'd' if is_stopd else '', code, len(found), pc, end, sites.count(key)))
                else:
                    addr_of[key] = found[0]
                    if is_stopd:
                        stopd_sites += sites.count(key)
            if not reason and stops:
                new_body = stop_site.sub(lambda s: 'ctx->stop_code = %su; ctx->status = SPU_STATUS_STOPPED_BY_STOP; ps3_lifted_stop_at(ctx, 0x%05Xu); return;' % (s.group(1), addr_of[(int(s.group(1), 0), not s.group(1).startswith('0x'))]), new_body)
            if not reason and 'spu_stop(' in new_body:
                reason = 'stop'
        if not reason:
            nh = len(halt_site.findall(new_body))
            new_body = halt_site.sub(lambda h: '%s ctx->status = SPU_STATUS_STOPPED_BY_HALT; ps3_lifted_halt_at(ctx, 0x%sU); return;' % (h.group(1), h.group(2)), new_body)
            halts += nh
            for needle in ('spu_halt(', 'g_spu_fast_tail', 'spu_register_function', 'spu_rc_add_pairs', 'spu_ibfast(', 'spu_tlc('):
                if needle in new_body:
                    reason = 'other'
        if policy and not reason:
            # policy-module code: every channel operation carries the address of its instruction (the interpreter resumes there when the channel would block), proved against the
            # module bytes: the channel statements of the function, in order, must be exactly the channel instructions of its extent. Any doubt: the function stays on the interpreter.
            annotated = annotate_channels(new_body, pc, next_pc[pc], word_at)
            if annotated is None:
                reason = 'channel'
                stop_notes.append('0x%X: channel statements do not match the channel instructions of the extent' % pc)
            else:
                new_body = annotated
            if not reason and policy['job_hook'] == pc:
                old_call = 'ctx->pc = ctx->gpr[5]._u32[0]; ctx->host_depth++; spu_indirect_branch(ctx);'
                if new_body.count(old_call) != 1:
                    sys.exit('job call site of 0x%X not found exactly once' % pc)
                new_body = new_body.replace(old_call, 'ctx->pc = ctx->gpr[5]._u32[0]; ps3_lifted_job_resolve(ctx); ctx->host_depth++; spu_indirect_branch(ctx);')
                job_hooks_done.append(pc)
        if reason:
            why[reason] += 1
            stub_reason[pc] = reason
            rows.append((pc, fname, 0))
            out_defs.append('void %s(spu_context* ctx) {\n    ctx->pc = 0x%Xu; ps3_lifted_escape(ctx);\n}\n' % (fname, pc))
            continue
        rows.append((pc, fname, 1))
        hook = ''
        if hooks and pc in hooks:
            hook = '    if (%s(ctx)) { SPU_RET(ctx); }   /* native replacement of this whole function (round 2); the macro is 0 unless the switch is on */\n' % hooks[pc]
            hooked.append(pc)
        out_defs.append('void %s(spu_context* ctx) {\n    PS3_JOBMOD_TRACE_ENTRY(ctx, 0x%X);\n%s%s}\n' % (fname, pc, hook, new_body))

    rows.sort()
    if policy and policy['job_hook'] is not None and policy['job_hook'] not in job_hooks_done:
        sys.exit('%s: the job call function 0x%X was not lifted' % (name, policy['job_hook']))
    if hooks and sorted(hooked) != sorted(hooks):
        sys.exit('%s: hook functions %s are not all lifted functions of the module' % (name, ['0x%X' % h for h in hooks if h not in hooked]))
    lifted = sum(1 for r in rows if r[2])
    # ---- code range: ELF twin or reachability
    roots = {entry_pc}
    for e in extra_roots:
        roots.add(int(e, 16) if isinstance(e, str) else e)
    # (address constants the module loads are NOT roots: they include data addresses that coincide with garbage "functions"; measured on
    #  the six modules that have an EBOT twin, the end of what is reachable from the entry and the extra roots is the end of .text,
    #  always below the first writable section)
    reach, todo = set(), [r for r in roots if r in graph]
    while todo:
        p = todo.pop()
        if p in reach:
            continue
        reach.add(p)
        todo.extend(graph.get(p, ()))
    t_reach = max((next_pc[p] for p in reach), default=base + 0x40)
    t_reach = (t_reach + 15) & ~15
    twin = twins.get(binary[:len(binary) - 32]) if twins and base == BASE else None
    if t_fixed:
        T, source = t_fixed, 'end of the ELF first (read-only) segment'
    elif twin and twin[0]:
        T, source = twin[0], 'ELF %s writable section start (reachability says 0x%X)' % (twin[1], t_reach)
        # (the address constants the module loads include data addresses that coincide with garbage "functions", so the static
        # reachability is only a lower-level cross-check here; the ELF layout decides)
    else:
        T, source = t_reach, 'reachable functions'
    assert base + 0x30 <= T <= base + len(binary)
    unsupp_in_range = 0
    prelude_names = [name + '_ibf_c']
    c = []
    c.append('/* %s -- do not edit.\n * input: spu_recomp_rc.c of %s (register-cached twins, Windows port lifter v200 + ibf)\n'
             ' * %d functions: %d lifted, %d escape stubs (plain %d, lossy %d, bad transfer %d, stop %d, other %d); %d halt assertion sites */\n'
             % (MARK, name, len(rows), lifted, len(rows) - lifted, why['plain_stub'], why['lossy'], why['bad_xfer'], why['stop'], why['other'], halts))
    if base != BASE:
        c.append('#define PS3_JOBMOD_WINDOW_LO 0x%Xu   /* this module starts below the job window (a task image) */' % base)
    c.append('#include "../jobmod_lifted_prelude.h"\n')
    c.append('static uint32_t s_ibf_c[%d];   /* per-site caches: pc << 14 | index + 1. Shared by every thread: an entry is a complete pair of a static table, so any value read is correct */' % max(nsites, 1))
    c.append('static spu_ibf_fn %s_ibf_find(uint32_t pc, uint32_t* c);\n' % name)
    for n, pc in sorted(names.items(), key=lambda x: x[1]):
        c.append('void %s(spu_context* ctx);' % n)
    c.append('')
    c.append('\n'.join(out_defs))
    # regenerated ibf lookup: binary search over this file's functions (any function of the file is a legal direct target)
    c.append('static const uint32_t %s_ibf_pc[%d] = {%s};' % (name, len(rows), ','.join('0x%Xu' % r[0] for r in rows)))
    c.append('static const spu_ibf_fn %s_ibf_fn[%d] = {%s};' % (name, len(rows), ','.join(r[1] for r in rows)))
    c.append('''static spu_ibf_fn %(n)s_ibf_find(uint32_t pc, uint32_t* c)
{
    const uint32_t v = __atomic_load_n(c, __ATOMIC_RELAXED);
    if (v && (v >> 14) == pc) { const uint32_t i = v & 0x3FFFu; return i == 0x3FFFu ? 0 : %(n)s_ibf_fn[i - 1u]; }
    uint32_t r = 0x3FFFu;   /* not an entry of this module (cached too: the table is static) */
    unsigned lo = 0, hi = %(count)d;
    while (lo < hi) { const unsigned mid = (lo + hi) / 2u; if (%(n)s_ibf_pc[mid] == pc) { r = mid + 1u; break; } if (%(n)s_ibf_pc[mid] < pc) lo = mid + 1u; else hi = mid; }
    __atomic_store_n(c, (pc << 14) | r, __ATOMIC_RELAXED);
    return r == 0x3FFFu ? 0 : %(n)s_ibf_fn[r - 1u];
}
''' % {'n': name, 'count': len(rows)})
    c_text = '\n'.join(c)
    for needle in ('lodx', 'g_spu_fast_tail', 'spu_register_function', 'spu_rc_add_pairs', 'spu_ibfast', 'spu_tlc('):
        if needle in c_text:
            sys.exit('residual %s in %s' % (needle, name))
    stub_pcs = {r[0] for r in rows if not r[2]}
    reach_stubs = sorted(p for p in reach if p in stub_pcs)
    return {'name': name, 'c_text': c_text, 'rows': rows, 'functions': len(rows), 'lifted': lifted, 'stubs': len(rows) - lifted,
            'reachable_stubs': ['0x%X:%s' % (p, stub_reason.get(p, '?')) for p in reach_stubs],
            'why': why, 'halts': halts, 'T': T, 'T_source': source, 'T_reach': t_reach, 'twin': twin[1] if twin else None,
            'reachable_functions': len(reach), 'stop_notes': stop_notes, 'stopd_sites': stopd_sites}


def emit(out, name, info, binary, base=BASE, policy=None):
    T = info['T']
    code = binary[:T - base]
    sig_off = (policy['ranges'][0][0] - base) if policy else 0        # a policy module's identity starts at its first code range
    sig_lo = int.from_bytes(binary[sig_off:sig_off + 8], 'little')
    sig_hi = int.from_bytes(binary[sig_off + 8:sig_off + 16], 'little')
    with open(os.path.join(out, name + '_rc.c'), 'w') as f:
        f.write(info['c_text'])
    r = ['/* %s -- do not edit. Rows and descriptor of %s: sorted {pc, function, flags} (1 lifted, 0 escape stub). */' % (MARK, name),
         '#include "../../spu_lifted_hybrid.h"']
    for pc, fname, flag in info['rows']:
        r.append('void %s(spu_context *);' % fname)
    r.append('static const ps3_spu_lifted_row %s_rows[%d] = {' % (name, len(info['rows'])))
    for pc, fname, flag in info['rows']:
        r.append('    {0x%05Xu,%s,%d},' % (pc, fname, flag))
    r.append('};')
    r.append('/* input spu_recomp_rc.c sha256 %s; code range [0x%X, 0x%X) from %s */' % (info['sha256_input'], base, T, info['T_source']))
    if policy:
        r.append('static const uint32_t %s_ranges[%d] = {%s};   /* the module\'s CODE ranges (its data lives between them) */' % (name, 2 * len(policy['ranges']), ','.join('0x%Xu,0x%Xu' % x for x in policy['ranges'])))
        fast = hash_ranges(binary, base, policy['ranges'])
        slow = fnv1a64(b''.join(bytes(binary[lo - base:hi - base]) for lo, hi in policy['ranges']))
    else:
        fast, slow = hash64w(code), fnv1a64(code)
    r.append('const ps3_spu_lifted_module %s_module = {' % name)
    r.append('    "%s", %d, 0x%05Xu, 0x%Xu, 0x%Xu,' % (name, info['image_id'], info['entry_pc'], policy['ranges'][0][0] if policy else base, T))
    r.append('    UINT64_C(0x%016X), UINT64_C(0x%016X),' % (slow, fast))
    r.append('    %s_rows, %d, UINT64_C(0x%016X), UINT64_C(0x%016X)%s };' % (name, len(info['rows']), sig_lo, sig_hi, (', %s_ranges, %d, %s' % (name, len(policy['ranges']), 'PS3_LIFTED_KIND_KERNEL' if policy['module_kind'] == 'kernel' else 'PS3_LIFTED_KIND_POLICY')) if policy else ''))
    open(os.path.join(out, name + '_module.c'), 'w').write('\n'.join(r) + '\n')


if __name__ == '__main__':
    main()
