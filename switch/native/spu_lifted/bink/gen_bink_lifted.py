#!/usr/bin/env python3
"""Mechanical adaptation of the Windows port's lifted Bink decoder (spu_0001_at_00673E80, register-cached twins) so it
compiles against THIS repository's native SPU runtime and runs through ps3_spu_executor.

usage: gen_bink_lifted.py --rc <spu_recomp_rc.c> --elf <EBOOT.elf> --elf-offset <hex> --out <dir>

Inputs (read only):
  --rc          infamous-recomp/spu/spu_0001_at_00673E80/spu_recomp_rc.c  (lifter output, never edited by hand)
  --elf         the user's own game EBOOT.elf; the SPU ELF embedded at --elf-offset is parsed in place (nothing is copied
                out of it except a hash and, for the stop sites, the address of each `stop` word)
Outputs (all under --out; existing files are replaced only when they carry this script's GENERATED marker):
  bink_lifted_rc.c    the adapted lifted translation unit
  bink_lifted_rows.c  the sorted {pc, function, genuine} rows the glue expands into the executor's linked image
  bink_lifted_meta.h  image identity: input sha256, code range, FNV-1a-64 of the loaded code, function counts

What is changed in the lifted text (everything else is byte-for-byte the lifter's output):
  1. the preamble (includes, SPU_FAST_XFER/g_spu_fast_tail TLS block) -> `#include "bink_lifted_prelude.h"`
  2. the tail after "/* Function table */" (desktop registry, pair registry, constructor) is dropped
  3. the 77 `ctx->pc = X; g_spu_trampoline_fn = spu_indirect_branch; return;` stubs (unresolved branch targets, desktop:
     fall back to its interpreter) -> `ctx->pc = X; ps3_lifted_escape(ctx);` (native: interpret from X)
  4. every `spu_stop(ctx); return;` -> `ps3_lifted_stop_at(ctx, <address of the stop word>); return;`
     (the address is read from the game's own SPU ELF and checked against the stop code the lifter emitted)
  5. every `spu_halt(ctx); return;` -> `ps3_lifted_halt_at(ctx, <address of the halting instruction>); return;`
  Channel and stop entry points are renamed by macros in bink_lifted_prelude.h, not by editing the text.
"""
import argparse, hashlib, os, re, struct, sys

MARK = 'GENERATED by gen_bink_lifted.py'
PREFIX = 'spu_0001_at_00673E80_rc_spu_func_'


def load_spu_ls(elf_path, offset):
    data = open(elf_path, 'rb').read()
    b = offset
    if data[b:b + 4] != b'\x7fELF':
        sys.exit('no ELF at offset 0x%X' % offset)
    machine = struct.unpack('>H', data[b + 18:b + 20])[0]
    if machine != 23:
        sys.exit('ELF at 0x%X is not an SPU ELF (machine %d)' % (offset, machine))
    entry = struct.unpack('>I', data[b + 24:b + 28])[0]
    phoff = struct.unpack('>I', data[b + 28:b + 32])[0]
    phentsize, phnum = struct.unpack('>HH', data[b + 42:b + 46])
    ls = bytearray(0x40000)
    exec_ranges = []
    for k in range(phnum):
        o = b + phoff + k * phentsize
        ptype, off, vaddr, _pa, filesz, memsz, flags, _al = struct.unpack('>IIIIIIII', data[o:o + 32])
        if ptype != 1:
            continue
        ls[vaddr:vaddr + filesz] = data[b + off:b + off + filesz]
        if flags & 1:
            exec_ranges.append((vaddr, vaddr + filesz))
    return entry, ls, exec_ranges


def fnv1a64(buf):
    h = 0xCBF29CE484222325
    for byte in buf:
        h ^= byte
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def hash64w(buf):
    """Same as ps3_spu_lifted_hash64w (spu_lifted_hybrid.c)."""
    M = 0xFFFFFFFFFFFFFFFF
    def mix(h, w):
        h = ((h ^ w) * 0x9E3779B97F4A7C15) & M
        return h ^ (h >> 32)
    h = [0x243F6A8885A308D3, 0x13198A2E03707344, 0xA4093822299F31D0, 0x082EFA98EC4E6C89]
    n = len(buf)
    i = 0
    while i + 32 <= n:
        for k in range(4):
            h[k] = mix(h[k], int.from_bytes(buf[i + 8 * k:i + 8 * k + 8], 'little'))
        i += 32
    while i + 8 <= n:
        h[0] = mix(h[0], int.from_bytes(buf[i:i + 8], 'little'))
        i += 8
    if i < n:
        h[0] = mix(h[0], int.from_bytes(bytes(buf[i:n]) + b'\0' * (8 - (n - i)), 'little'))
    return mix(mix(mix(mix(h[0], h[1]), h[2]), h[3]), n)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rc', required=True)
    ap.add_argument('--elf', required=True)
    ap.add_argument('--elf-offset', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    raw = open(a.rc, 'rb').read()
    text = raw.decode('utf-8')
    sha = hashlib.sha256(raw).hexdigest()
    entry, ls, exec_ranges = load_spu_ls(a.elf, int(a.elf_offset, 0))
    if len(exec_ranges) != 1:
        sys.exit('expected exactly one executable PT_LOAD, got %r' % (exec_ranges,))
    code_begin, code_end = exec_ranges[0]
    code_hash = fnv1a64(ls[code_begin:code_end])
    code_hash_fast = hash64w(ls[code_begin:code_end])

    cut_tail = text.index('/* Function table */')
    body = text[:cut_tail]
    tail = text[cut_tail:]
    # The dropped tail must be exactly the desktop registration machinery, nothing executable.
    for needle in ('spu_function_table', 'spu_recomp_register', 's_spu_rc_pairs', 'spu_rc_add_pairs'):
        if needle not in tail:
            sys.exit('tail does not look like the registry block (missing %s)' % needle)
    if re.search(r'^void ' + re.escape(PREFIX), tail, re.M):
        sys.exit('a function definition lies after the Function table marker')
    first_proto = body.index('/* v95: register-cached twins')
    preamble, rest = body[:first_proto], body[first_proto:]
    if 'SPU_FAST_XFER' not in preamble or 'g_spu_fast_tail' not in preamble:
        sys.exit('unexpected preamble')

    def_re = re.compile(r'^void (' + re.escape(PREFIX) + r'([0-9A-F]{8}))\(spu_context\* ctx\) \{\n(.*?)^\}\n', re.M | re.S)
    defs = list(def_re.finditer(rest))
    pcs = [int(m.group(2), 16) for m in defs]
    if len(set(pcs)) != len(pcs):
        sys.exit('duplicate function pcs')
    names = {m.group(1) for m in defs}
    protos = set(re.findall(r'^void (' + re.escape(PREFIX) + r'[0-9A-F]{8})\(spu_context\* ctx\);', rest, re.M))
    if protos != names:
        sys.exit('prototypes != definitions (%d vs %d)' % (len(protos), len(names)))

    stub_body = re.compile(r'    ctx->pc = (0x[0-9A-F]+)u; g_spu_trampoline_fn = spu_indirect_branch; return;\n')
    stop_site = re.compile(r'ctx->stop_code = (0x[0-9A-F]+)u; ctx->status = SPU_STATUS_STOPPED_BY_STOP; spu_stop\(ctx\); return;')
    halt_site = re.compile(r'(fprintf\(stderr, "\[spu\] HALT-ASSERT \w+ pc=0x([0-9A-F]+) img=%d\\n", ctx->image_id\);) '
                           r'ctx->status = SPU_STATUS_STOPPED_BY_HALT; spu_halt\(ctx\); return;')

    rows = []          # (pc, name, genuine)
    stats = {'stubs': 0, 'stops': 0, 'halts': 0, 'lossy': 0}
    stop_log = []
    unresolved = []

    def rewrite(m):
        name, pchex, fbody = m.group(1), m.group(2), m.group(3)
        pc = int(pchex, 16)
        sm = stub_body.fullmatch(fbody)
        if sm:
            if int(sm.group(1), 16) != pc:
                sys.exit('stub pc/name mismatch in ' + name)
            stats['stubs'] += 1
            rows.append((pc, name, 0))
            return 'void %s(spu_context* ctx) {\n    ctx->pc = %su; ps3_lifted_escape(ctx);\n}\n' % (name, sm.group(1))
        lossy = 2 if 'spu_unsupported(' in fbody else 0
        if lossy:
            stats['lossy'] += 1
        rows.append((pc, name, 1 | lossy))

        def stop_sub(sm2):
            code = int(sm2.group(1), 16)
            addr = None
            for at in range(pc, min(pc + 0x4000, 0x40000), 4):
                word = struct.unpack('>I', bytes(ls[at:at + 4]))[0]
                if (word >> 21) == 0:    # SPU `stop`: opcode 0 in the top 11 bits, 14-bit signal type in bits 0..13
                    if (word & 0x3FFF) == code:
                        addr = at
                    break
            stats['stops'] += 1
            if addr is None:
                # The lifter also decoded data words (constant pools) as code; such a "stop" has no stop word at its
                # block in the ELF image. It can only run if the guest jumps into a constant pool: refuse at run time.
                unresolved.append((pc, code))
                return 'ctx->stop_code = %su; ctx->status = SPU_STATUS_STOPPED_BY_STOP; ps3_lifted_stop_at(ctx, PS3_LIFTED_NO_STOP_WORD); return;' % sm2.group(1)
            stop_log.append((addr, code))
            return 'ctx->stop_code = %su; ctx->status = SPU_STATUS_STOPPED_BY_STOP; ps3_lifted_stop_at(ctx, 0x%05Xu); return;' % (sm2.group(1), addr)

        def halt_sub(hm):
            stats['halts'] += 1
            return '%s ctx->status = SPU_STATUS_STOPPED_BY_HALT; ps3_lifted_halt_at(ctx, 0x%sU); return;' % (hm.group(1), hm.group(2))

        nb = stop_site.sub(stop_sub, fbody)
        nb = halt_site.sub(halt_sub, nb)
        return 'void %s(spu_context* ctx) {\n%s}\n' % (name, nb)

    new_rest = def_re.sub(rewrite, rest)
    for needle in ('spu_stop(', 'spu_halt(ctx)', 'g_spu_fast_tail', 'spu_register_function', 'spu_rc_add_pairs'):
        if needle in new_rest:
            sys.exit('residual %s after adaptation' % needle)
    # Every direct transfer must target a definition of this TU and store the pc its name encodes.
    xfers = re.findall(r'ctx->pc = (0x[0-9A-F]+); SPU_FAST_XFER\(ctx, (\w+)\)', new_rest)
    bare = re.findall(r'SPU_FAST_XFER\(ctx, (\w+)\)', new_rest)
    if len(xfers) != len(bare):
        sys.exit('SPU_FAST_XFER without a constant pc store')
    for pchex, target in xfers:
        if target not in names:
            sys.exit('transfer target outside the TU: ' + target)
        if int(pchex, 16) != int(target[len(PREFIX):], 16):
            sys.exit('transfer pc/name mismatch %s %s' % (pchex, target))
    rows.sort()

    os.makedirs(a.out, exist_ok=True)
    outputs = {}
    outputs['bink_lifted_rc.c'] = (
        '/* %s -- do not edit.\n'
        ' * input: spu_recomp_rc.c sha256 %s (register-cached twins of spu_0001_at_00673E80, the inFAMOUS Bink movie decoder)\n'
        ' * %d functions (%d lossy: contain unliftable words), %d escape stubs, %d stop sites, %d halt sites, %d SPU_FAST_XFER sites verified (pc == target name). */\n'
        '#include "bink_lifted_prelude.h"\n\n%s'
        % (MARK, sha, len(rows), stats['lossy'], stats['stubs'], stats['stops'], stats['halts'], len(xfers), new_rest.lstrip('\n')))
    rows_c = ['/* %s -- do not edit. Sorted {pc, function, flags} rows of bink_lifted_rc.c; flags: 1 genuine lifted code, 2 lossy (the lifter could not translate a word; data decoded as code), 0 escape stub. */' % MARK,
              '#include "../../spu_lifted_hybrid.h"']
    for _pc, name, _g in rows:
        rows_c.append('void %s(spu_context *);' % name)
    rows_c.append('const ps3_spu_lifted_row ps3_bink_lifted_rows[%d]={' % len(rows))
    for pc, name, g in rows:
        rows_c.append('    {0x%05Xu,%s,%d},' % (pc, name, g))
    rows_c.append('};')
    rows_c.append('const unsigned ps3_bink_lifted_row_count=%du;' % len(rows))
    outputs['bink_lifted_rows.c'] = '\n'.join(rows_c) + '\n'
    outputs['bink_lifted_meta.h'] = (
        '/* %s -- do not edit. */\n#ifndef PS3_BINK_LIFTED_META_H\n#define PS3_BINK_LIFTED_META_H\n'
        '#define PS3_BINK_LIFTED_INPUT_SHA256 "%s"\n'
        '#define PS3_BINK_LIFTED_ENTRY_PC 0x%05Xu\n'
        '#define PS3_BINK_LIFTED_CODE_BEGIN 0x%05Xu\n#define PS3_BINK_LIFTED_CODE_END 0x%05Xu\n'
        '#define PS3_BINK_LIFTED_CODE_HASH UINT64_C(0x%016X)\n#define PS3_BINK_LIFTED_CODE_HASH_FAST UINT64_C(0x%016X)\n'
        '#define PS3_BINK_LIFTED_FUNCTIONS %du\n#define PS3_BINK_LIFTED_STUBS %du\n#endif\n'
        % (MARK, sha, entry, code_begin, code_end, code_hash, code_hash_fast, len(rows), stats['stubs']))
    for name, content in outputs.items():
        path = os.path.join(a.out, name)
        if os.path.exists(path) and MARK not in open(path, errors='replace').read(400):
            sys.exit('REFUSED: %s exists and is not a generated file' % path)
    for name, content in outputs.items():
        with open(os.path.join(a.out, name), 'w') as f:
            f.write(content)
    print('rc sha256 %s' % sha)
    print('functions=%d stubs=%d lossy=%d stops=%d halts=%d fast_xfers=%d' % (len(rows), stats['stubs'], stats['lossy'], stats['stops'], stats['halts'], len(xfers)))
    print('entry=0x%X code=[0x%X,0x%X) fnv1a64=0x%016X hash64w=0x%016X' % (entry, code_begin, code_end, code_hash, code_hash_fast))
    print('stop sites (address:code): ' + ' '.join('0x%X:0x%X' % s for s in stop_log))
    print('stop sites without a stop word in the ELF image (data decoded as code), function:code: ' + ' '.join('0x%X:0x%X' % s for s in unresolved))


if __name__ == '__main__':
    main()
