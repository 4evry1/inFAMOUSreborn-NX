#!/usr/bin/env python3
"""Generate the native linked-image table for one lifted SPU TU.

Usage: gen_spu_linked_image.py <generated rc.c> <symbol prefix> <image name> <output .c>

The lifter names every function <prefix><8 hex digits of its LS pc>. This script fails (exit 1) unless:
  * every definition `void <prefix>XXXXXXXX(spu_context* ctx) {` has a unique pc;
  * the TU's own pair registry (s_spu_rc_pairs) lists exactly the same functions;
  * every `ctx->pc = 0x..; SPU_XFER(ctx, <prefix>YYYYYYYY)` stores the pc encoded in the target name;
  * every SPU_XFER target is a definition of this TU.
Output: a sorted const table {pc, function} plus the descriptor, with the input sha256 in the header comment.
"""
import hashlib, re, sys

def main():
    src, prefix, name, out = sys.argv[1:5]
    raw = open(src, 'rb').read(); text = raw.decode('utf-8')
    defs = re.findall(r'^void (%s([0-9A-F]{8}))\(spu_context\* ctx\) \{$' % re.escape(prefix), text, re.M)
    pcs = [int(h, 16) for _, h in defs]
    if not defs or len(set(pcs)) != len(pcs): sys.exit('duplicate or missing definitions')
    names = {f for f, _ in defs}
    pairs = set(re.findall(r'^\s*\(const void\*\)\w+, \(const void\*\)(%s[0-9A-F]{8}),$' % re.escape(prefix), text, re.M))
    if pairs != names: sys.exit('pair registry != definitions (%d vs %d)' % (len(pairs), len(names)))
    xfers = re.findall(r'ctx->pc = (0x[0-9A-Fa-f]+); SPU_XFER\(ctx, (\w+)\)', text)
    bare = re.findall(r'SPU_XFER\(ctx, (\w+)\)', text)
    if len(xfers) != len(bare): sys.exit('SPU_XFER without a preceding constant pc store')
    for pc, target in xfers:
        if target not in names: sys.exit('XFER target outside this TU: ' + target)
        if int(pc, 16) != int(target[len(prefix):], 16): sys.exit('XFER pc/name mismatch: %s %s' % (pc, target))
    rows = sorted(zip(pcs, (f for f, _ in defs)))
    sha = hashlib.sha256(raw).hexdigest()
    sym = 'ps3_' + re.sub(r'\W', '_', name) + '_linked_image'
    with open(out, 'w') as o:
        o.write('/* GENERATED by native/tools/gen_spu_linked_image.py -- do not edit.\n')
        o.write(' * input: %s sha256 %s\n' % (src[src.index('source/'):] if 'source/' in src else src, sha))
        o.write(' * %d functions; %d SPU_XFER sites verified (pc == target name); pair registry == definitions. */\n'
                % (len(rows), len(xfers)))
        o.write('#include "../adapters/spu_linked_image.h"\n')
        for _, f in rows: o.write('void %s(spu_context *);\n' % f)
        o.write('static const ps3_spu_lifted_function functions[%d]={\n' % len(rows))
        for pc, f in rows: o.write('    {0x%05Xu,%s},\n' % (pc, f))
        o.write('};\n')
        o.write('const ps3_spu_linked_image %s={"%s",functions,%du};\n' % (sym, name, len(rows)))
    print('%s functions=%d xfer_sites=%d input_sha256=%s symbol=%s' % (out, len(rows), len(xfers), sha, sym))

if __name__ == '__main__':
    main()
