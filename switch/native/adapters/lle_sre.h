#ifndef NATIVE_LLE_SRE_H
#define NATIVE_LLE_SRE_H
#include "compiled_code.h"
#include "guest_space.h"
#include "ppu_recomp.h"
#include <cstddef>
#include <cstdint>

/* Decision 33, phase B1a: run Sony's real libsre.prx where the native runtime would otherwise run
 * the hand-written cellSpurs/cellSync HLE. Nothing here is compiled into a build without
 * PS3_NATIVE_LLE_SRE, and no type in this header exists when the flag is off.
 *
 * Three responsibilities, all guest-address-level:
 *   1. map the module image once at 0x30000000 (zeroed to the module's full extent, image copied in)
 *      and publish that extent as one writable RAM range;
 *   2. answer "does the module export this NID, and which OPD is it?" from a sorted table;
 *   3. run one export: resolve NID -> OPD -> {code, toc}, swap the TOC over the call, restore it.
 *
 * The image bytes and the export table are generated per build by tools/lle/gen_lle_sre_glue.py and
 * are reachable through `extern const LibsreModuleDescription libsre_module_description`, so this
 * header and its unit stay free of firmware-derived data. */

struct LibsreExportEntry {
    uint32_t nid;
    uint32_t opd;
    const char *library;
};

struct LibsreModuleDescription {
    uint32_t base;
    uint32_t toc;
    uint32_t image_size;
    uint32_t mapped_extent;
    const unsigned char *image;
    const LibsreExportEntry *exports;
    size_t export_count;
};

extern const LibsreModuleDescription libsre_module_description;

// The lifted unit's own function table (ppu_recomp_000.cpp, generated by lift_libsre.sh). It is
// declared here rather than by including that unit's ppu_recomp.h, because a build also has a
// ppu_recomp.h of its own -- the GAME's generated ABI header -- and one translation unit cannot carry
// both. The lifetime is the program's, and lle_sre.cpp checks every entry it returns.
extern "C" const func_entry libsre_function_table[];
extern "C" const uint64_t libsre_function_table_count;

enum class LleSreMappingStatus { Mapped, AlreadyMapped, ExtentTooSmall, ImageTooLarge, EmptyExports };

enum class LleSreRouteStatus {
    Routed,       // the lifted function ran to its own return
    NotExported,  // the NID belongs to no libsre library: the caller must use its own dispatch
    Unavailable   // exported, but the module is not mapped yet
};

struct LleSreImageMapping {
    uint32_t base;
    uint64_t length;
    bool writable;
};

/* The module's extent as a composition would declare it next to its own RAM ranges. The range is
 * rejected (false) if it overlaps any of `declared` or if any declared range already covers it. */
bool lle_sre_image_mapping(const LleSreImageMapping *declared, size_t declared_count,
    LleSreImageMapping *mapping);

/* Every export must lie inside the mapped extent, well formed, and strictly sorted by NID. */
LleSreMappingStatus lle_sre_mapping_admit();

bool lle_sre_mapping_admitted();

/* Validate the generated description without mapping anything (used by the composition before it
 * commits its RAM declarations). */
LleSreMappingStatus lle_sre_mapping_check();

/* Writes the generated image at the base through `memory`, leaving the rest of the extent zero.
 * Must run once, after the RAM range has been committed and before any route. */
LleSreMappingStatus lle_sre_map_image(const ps3_guest_memory *memory);

uint32_t lle_sre_base();
uint32_t lle_sre_toc();
uint32_t lle_sre_mapped_extent();

bool lle_sre_export_opd(uint32_t nid, uint32_t *opd);
bool lle_sre_exports_nid(uint32_t nid);

/* Reads the OPD through `memory` and calls the lifted function at its code address with the OPD's
 * TOC in r2. The caller's r2 and r1 are restored; r3..r12 are left as the callee left them. */
LleSreRouteStatus lle_sre_call_export(uint32_t nid, ppu_context *cpu, const ps3_guest_memory *memory);

/* The lifted table the compiled-code dispatcher consults after the game's own. */
ps3_compiled_code_lookup lle_sre_compiled_code_lookup();

/* The production lookup: the game's table first, the lifted module second. `game` is the port the
 * composition built from its PpuCompiledCodeTable and is borrowed for the life of the process. */
ps3_compiled_code_lookup lle_sre_chained_compiled_code_lookup(ps3_compiled_code_lookup game);
// Nested calls into the game from lifted code (a function pointer held by guest memory) carry the
// game's TOC. Active only while a libsre frame is on this thread's stack.
bool lle_sre_callback_toc(uint64_t *toc);

#endif
