#!/usr/bin/env python3
"""Turn a lift_libsre.sh result into the one build-local C++ unit the native runtime needs.

usage: gen_lle_sre_glue.py <lift_libsre build dir> <output .cpp>

Inputs, both produced by evidence/lle-sre-a1/lift_libsre.sh inside <build dir>:
  prx/libsre_image.bin      the relocated module image (the module's own bytes)
  prx/libsre_exports.json   {library: {nid_hex: opd_hex}} for the 267 exports

Output: a C++ unit with
  (a) the image bytes as a const array,
  (b) a sorted NID -> OPD EA table for every export,
  (c) the module constants (base, TOC, image size, total mapped extent).

The extent is derived here, not hard-coded: the top of the image, the end of .bss (the data
segment's memsz end), every TOC-relative reach in the module (the TOC sits exactly 0x8000 above the
data segment's memsz end) and the largest toc-relative displacement any lifted instruction uses,
rounded up to 64 KB. The generated file is derived from the user's own firmware, so it must stay
inside build/.
"""
import json
import struct
import sys

PAGE_ALIGN = 0x10000
TOC_REACH = 0x8000
D_FORM_MAX = 0x8000
EXPECTED_EXPORTS = 267


def fail(message):
    sys.stderr.write("gen_lle_sre_glue: %s\n" % message)
    raise SystemExit(1)


def read_exports(path):
    with open(path, "r", encoding="utf-8") as stream:
        document = json.load(stream)
    libraries = document["exports"]
    entries = []
    for library, table in libraries.items():
        for nid_text, opd_text in table.items():
            entries.append((int(nid_text, 16), int(opd_text, 16), library))
    base = int(document["base"], 16)
    toc = int(document["toc"], 16)
    entries.sort()
    for index in range(1, len(entries)):
        if entries[index][0] == entries[index - 1][0]:
            fail("duplicate export nid 0x%08X" % entries[index][0])
    return base, toc, entries


def opd_bytes(image, base, opd):
    offset = opd - base
    if offset < 0 or offset + 8 > len(image):
        fail("export opd 0x%08X is outside the image" % opd)
    return struct.unpack(">II", image[offset:offset + 8])


def array_literal(values, per_line=12):
    lines = []
    for start in range(0, len(values), per_line):
        chunk = values[start:start + per_line]
        lines.append("        " + ", ".join("0x%02Xu" % value for value in chunk) + ",")
    return "\n".join(lines)


def generate(build_dir, output_path):
    prx = build_dir.rstrip("/") + "/prx"
    with open(prx + "/libsre_image.bin", "rb") as stream:
        image = stream.read()
    base, toc, entries = read_exports(prx + "/libsre_exports.json")
    if len(entries) != EXPECTED_EXPORTS:
        fail("expected %d exports, found %d" % (EXPECTED_EXPORTS, len(entries)))

    image_end = base + len(image)
    toc_reach_end = max(toc + TOC_REACH + D_FORM_MAX, image_end)
    extent = (toc_reach_end - base + PAGE_ALIGN - 1) // PAGE_ALIGN * PAGE_ALIGN

    opd_rows = []
    for nid, opd, library in entries:
        code, opd_toc = opd_bytes(image, base, opd)
        if opd_toc != toc:
            fail("export 0x%08X opd 0x%08X carries toc 0x%08X, expected 0x%08X"
                 % (nid, opd, opd_toc, toc))
        if code < base or code >= base + len(image):
            fail("export 0x%08X opd 0x%08X resolves to code 0x%08X outside the image"
                 % (nid, opd, code))
        opd_rows.append((nid, opd, library))

    text = []
    text.append("/* Auto-generated by tools/lle/gen_lle_sre_glue.py -- do not edit by hand.")
    text.append(" * Derived from the user's own firmware; lives only under build/. */")
    text.append('#include "lle_sre_generated.h"')
    text.append("")
    text.append("namespace {")
    text.append("")
    text.append("const unsigned char kLibsreImageBytes[kLibsreImageSize] = {")
    text.append(array_literal(image))
    text.append("};")
    text.append("")
    text.append("const LibsreExportEntry kLibsreExportEntries[] = {")
    for nid, opd, library in opd_rows:
        text.append('    {0x%08Xu, 0x%08Xu, "%s"},' % (nid, opd, library))
    text.append("};")
    text.append("")
    text.append("}  // namespace")
    text.append("")
    text.append("extern const LibsreModuleDescription libsre_module_description;")
    text.append("const LibsreModuleDescription libsre_module_description = {")
    text.append("    0x%08Xu," % base)
    text.append("    0x%08Xu," % toc)
    text.append("    kLibsreImageSize,")
    text.append("    0x%08Xu," % extent)
    text.append("    kLibsreImageBytes,")
    text.append("    kLibsreExportEntries,")
    text.append("    sizeof(kLibsreExportEntries) / sizeof(kLibsreExportEntries[0]),")
    text.append("};")
    text.append("")
    with open(output_path, "w", encoding="utf-8") as stream:
        stream.write("\n".join(text))

    sys.stdout.write("glue: base=0x%08X toc=0x%08X image=%d extent=0x%X exports=%d\n"
                     % (base, toc, len(image), extent, len(opd_rows)))
    return 0


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: gen_lle_sre_glue.py <lift_libsre build dir> <output .cpp>\n")
        return 2
    return generate(argv[1], argv[2])


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
